// Writes src/generated/registry.js, the list of content modules and widget files
// the app shell imports. src/generated/ is gitignored, so both the build and the
// unit tests (vitest globalSetup) call this; a fresh clone then works either way.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.join(ROOT, p);

export function writeRegistry() {
  const contentFiles = fs.readdirSync(rel('src/content')).filter((f) => /^\d\d-.*\.js$/.test(f)).sort();
  const widgetFiles = fs.readdirSync(rel('src/widgets')).filter((f) => f.endsWith('.js')).sort();
  fs.mkdirSync(rel('src/generated'), { recursive: true });
  fs.writeFileSync(rel('src/generated/registry.js'), [
    '// Generated by tools/registry.mjs. Do not edit.',
    ...contentFiles.map((f, i) => `import c${i} from '../content/${f}';`),
    ...widgetFiles.map((f, i) => `import * as w${i} from '../widgets/${f}';`),
    `export const modules = [${contentFiles.map((_, i) => `c${i}`).join(', ')}];`,
    `export const widgetModules = [${widgetFiles.map((_, i) => `w${i}`).join(', ')}];`,
    '',
  ].join('\n'));
  return { contentFiles, widgetFiles };
}

// vitest globalSetup entry point
export default function setup() { writeRegistry(); }
